export const PROMPT_D2_TEMPLATE = `에피소드 {episodeNumber}의 전체 대본(대사)을 작성하라.

핵심 원칙: 글이 먼저다. 영상을 떠올리기 전에 대사와 감정을 완성하라.
대사가 강해야 영상이 강해진다. 이미지부터 떠올리면 양산형이 된다.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
【대사 작성 원칙】
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
- 각 캐릭터의 말투, 성격, speech_tone을 대사에 완전히 반영하라.
- 대사는 호흡 단위로 끊어라. 긴 대사는 여러 줄로 나눠라.
- 가장 중요한 대사는 가장 짧고 느리게. 핵심 대사일수록 단순해야 한다.
- 감정 태그만 읽어도 에피소드 전체의 감정 곡선이 느껴져야 한다.
- 무음 간격(대사 없는 샷)도 의도적으로 설계하라. 침묵이 대사보다 강할 때가 있다.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
【대사-영상 관계 원칙】 ← 가장 중요
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
대사와 영상이 같은 말을 하면 안 된다 (동어반복 금지).
모든 대사에 dialogue_visual_rel을 명시하라:

- "complement": 대사가 A를 말하면, 화면은 A의 원인이나 결과를 보여준다.
  예: 대사 "무섭다" → 화면: 공포의 원인(거대한 그림자)을 보여줌
- "contrast": 대사와 화면이 반대다. 이 긴장이 시네마틱의 핵심이다.
  예: 대사 "괜찮아" → 화면: 떨리는 손, 숨겨진 눈물
- "extend": 대사가 끝난 뒤 화면이 말이 닿지 못한 여운을 보여준다.
  예: 대사 "그 여름" → 화면: 녹아내리는 아이스크림, 빈 그네

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
【출력 형식】
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
씬별로:
- scene_number: 씬 번호
- emotion_arc: 이 씬의 감정 흐름 한 줄 (예: "불안→경계→신뢰의 실마리→의심 회귀")
- dialogues: 대사 목록
  각 대사마다:
  - order_index: 씬 내 순번 (0부터 시작)
  - speaker_asset: 화자 asset_id
  - text: 대사 텍스트 (캐릭터 말투 완전 반영)
  - emotion: 감정 태그 (한 단어 또는 짧은 구)
  - intensity: 감정 강도 1~5 (1=담담, 3=중간, 5=폭발)
  - timing_hint: "beat" (짧은 여백 후) / "pause" (긴 침묵 후) / "rapid" (앞 대사에 바로 받아치기)
  - dialogue_visual_rel: "complement" / "contrast" / "extend" 중 하나 (동어반복 금지)
  - acting_direction: TTS 연기 지시 — 속도, 톤, 질감을 구체적으로
    (예: "속삭이듯, 마지막 단어에서 목이 메임" / "겨우 참고 있는 분노, 짧게 끊어서")

JSON 배열로 출력. JSON 외 다른 텍스트 없이.

=== 에피소드 씬 골격 ===
{skeletonJson}
=== 캐릭터 프로필 (말투/성격을 대사에 완전히 반영할 것) ===
{characterProfiles}`
